<?php

declare(strict_types=1);

namespace App\Services;

use App\Models\NginxMapping;

/**
 * Generates Nginx stream and HTTP configuration for port forwarding.
 *
 * Winbox proxies are `stream {}`-context directives, written to
 * config: vpnpanel.paths.nginx_stream_conf (/etc/nginx/stream.d/mikrotik.conf),
 * which nginx.conf includes *inside* a top-level `stream {}` block. The file
 * therefore holds bare upstream/server blocks — no wrapping `stream {}`.
 * WebFig HTTP servers go to config: vpnpanel.paths.nginx_conf
 * (/etc/nginx/conf.d/mikrotik.conf, included inside `http {}`).
 */
class NginxConfigGeneratorService
{
        /**
         * Generate the stream-context directives (Winbox TCP proxies).
         */
        public function generateStreamConfig(): string
        {
            $winboxMappings = NginxMapping::with('mikrotik')
                ->where('conn_type', 'winbox')
                ->where('is_enabled', true)
                ->get();

            if ($winboxMappings->isEmpty()) {
                return "# No Winbox mappings configured (generated by VPN Panel)\n";
            }

            $lines = [
                '# MikroTik Winbox stream proxies',
                '# Generated by VPN Panel on ' . now()->toDateTimeString(),
                '# Included from the top-level stream block in nginx.conf.',
                '',
            ];

            foreach ($winboxMappings as $mapping) {
                $mikrotik = $mapping->mikrotik;
                $upstreamName = $mapping->upstream_name;
                $internalIp = $mikrotik->vpn_ip;
                $internalPort = $mikrotik->winbox_internal_port;
                $publicPort = $mapping->public_port;

                $lines[] = "upstream {$upstreamName} {";
                $lines[] = "    server {$internalIp}:{$internalPort};";
                $lines[] = '}';
                $lines[] = '';
                $lines[] = 'server {';
                $lines[] = "    listen {$publicPort};";
                $lines[] = "    proxy_pass {$upstreamName};";
                $lines[] = '}';
                $lines[] = '';
            }

            return implode("\n", $lines) . "\n";
        }

        /**
         * Generate the HTTP-only configuration (WebFig proxy servers).
         */
        public function generateHttpConfig(): string
        {
            $webfigMappings = NginxMapping::with('mikrotik')
                ->where('conn_type', 'webfig')
                ->where('is_enabled', true)
                ->get();

            if ($webfigMappings->isEmpty()) {
                return "# No WebFig mappings configured (generated by VPN Panel)\n";
            }

            $lines = [
                '# MikroTik WebFig HTTP proxies',
                '# Generated by VPN Panel on ' . now()->toDateTimeString(),
                '',
            ];

            foreach ($webfigMappings as $mapping) {
                $mikrotik = $mapping->mikrotik;
                $internalIp = $mikrotik->vpn_ip;
                $internalPort = $mikrotik->webfig_internal_port;
                $publicPort = $mapping->public_port;

                $lines[] = 'server {';
                $lines[] = "    listen {$publicPort};";
                $lines[] = '    server_name ' . config('vpnpanel.domain') . ';';
                $lines[] = '';
                $lines[] = '    location / {';
                $lines[] = "        proxy_pass http://{$internalIp}:{$internalPort};";
                $lines[] = '        proxy_set_header Host $host;';
                $lines[] = '        proxy_set_header X-Real-IP $remote_addr;';
                $lines[] = '        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;';
                $lines[] = '        proxy_set_header X-Forwarded-Proto $scheme;';
                $lines[] = '    }';
                $lines[] = '}';
                $lines[] = '';
            }

            return implode("\n", $lines) . "\n";
        }

        /**
         * Combined config (legacy view/API compatibility: stream + http).
         */
        public function generate(): string
        {
            return $this->generateStreamConfig() . "\n" . $this->generateHttpConfig();
        }

        /**
         * Validate nginx configuration syntax.
         *
         * An empty file (no mappings yet) is valid — nginx accepts an empty
         * include. Only structural problems are rejected.
         */
        public function validate(string $config): array
        {
            $errors = [];

            if (substr_count($config, '{') !== substr_count($config, '}')) {
                $errors[] = 'Mismatched braces';
            }

            return $errors;
        }
}
