<?php

declare(strict_types=1);

namespace App\Services;

use App\Contracts\FileStore;
use App\Models\Ikev2User;
use Illuminate\Support\Facades\Log;

/**
 * Generates and deploys IKEv2 configuration for strongswan.
 */
class Ikev2ConfigDeployService
{
    public function __construct(
        private readonly FileStore $fileStore,
    ) {
    }

    /**
     * Deploy IKEv2 configuration (ipsec.conf, ipsec.secrets, charon settings).
     */
    public function deploy(): void
    {
            if (config('vpnpanel.ikev2.auth_mode', 'certificate') === 'certificate') {
                // hwdsl2/Libreswan already accepts any client certificate issued by
                // the server CA through `conn ikev2-cp` (rightca=%same), so there is
                // no per-user ipsec configuration to write.
                Log::info('IKEv2 auth mode is certificate; skipping per-user ipsec config deploy');

                return;
            }

            $users = Ikev2User::active()->get();

        $ipsecConf = $this->generateIpsecConf($users);
        $ipsecSecrets = $this->generateIpsecSecrets($users);
        $charonConf = $this->generateCharonConf($users);

        // Deploy ke filesystem
        $this->fileStore->put('/etc/ipsec.d/panel-ikev2.conf', $ipsecConf);
        $this->fileStore->put('/etc/ipsec.d/panel-ikev2.secrets', $ipsecSecrets);
        $this->fileStore->put('/etc/ipsec.d/panel-ikev2-charon.conf', $charonConf);

        Log::info("IKEv2 configuration deployed for {$users->count()} users");
    }

    /**
     * Generate ipsec.conf snippet untuk IKEv2 clients.
     */
    private function generateIpsecConf(iterable $users): string
        {
            $connections = '';
            foreach ($users as $user) {
                if (empty($user->assigned_ip)) {
                    continue;
                }

                $connections .= "
    conn ikev2-{$user->username}
        left=%any
        leftid=@{$user->username}
        leftauth=eap-mschapv2
        leftsourceip={$user->assigned_ip}
        right=%any
        rightid=@{$user->username}
        rightauth=eap-mschapv2
        auto=add
    ";
            }

            return <<<EOT
    # IKEv2 configuration generated by VPN Panel
    # DO NOT EDIT - this file is managed by the panel

    {$connections}
    EOT;
        }

    /**
     * Generate ipsec.secrets untuk EAP authentication.
     */
    private function generateIpsecSecrets(iterable $users): string
    {
        $secrets = "# IKEv2 secrets generated by VPN Panel\n# DO NOT EDIT - this file is managed by the panel\n\n";

        foreach ($users as $user) {
            $secrets .= "{$user->username} : EAP \"{$user->password}\"\n";
        }

        return $secrets;
    }

    /**
     * Generate charon.conf untuk enable EAP-MSCHAPv2.
     */
    private function generateCharonConf(iterable $users): string
    {
        return <<<EOT
# charon configuration for IKEv2 with EAP-MSCHAPv2
# DO NOT EDIT - this file is managed by the panel

charon {
    load_modular = yes
    unload_modular = no
    multiple_authentication = yes
    i_dont_care_about_security = yes
    
    # Enable EAP-MSCHAPv2
    eap-mschapv2 {
        use_esp = yes
    }
    
    # Logging
    filelog {
        /var/log/ipsec.log {
            time_format = %b %e %T
            default = yes
        }
    }
}

EOT;
    }
}
