<?php

declare(strict_types=1);

namespace App\Services;

use App\Models\Mikrotik;
use Illuminate\Support\Str;

/**
 * Generates RouterOS configuration scripts for MikroTik.
 */
class RouterOSGeneratorService
{
    /**
     * Generate complete RouterOS script for L2TP client.
     */
    public function generate(Mikrotik $mikrotik): string
    {
        $vpnServer = config('vpnpanel.domain');
        $username = $mikrotik->vpn_username;
            $password = $mikrotik->vpnPassword();
        $ip = $mikrotik->vpn_ip;
        $psk = config('vpnpanel.psk');

        $script = <<<ROUTEROS
# RouterOS L2TP/IPSec Client Configuration
# Generated by VPN Panel on {$this->now()}
# Site: {$mikrotik->site_name}
# VPN Server: {$vpnServer}
# Username: {$username}
# VPN IP: {$ip}

# Remove existing L2TP client if exists
/interface l2tp-client remove [find name="l2tp-out1"]

# Create L2TP client interface
/interface l2tp-client add \\
    name=l2tp-out1 \\
    connect-to={$vpnServer} \\
    user={$username} \\
    password={$password} \\
    use-ipsec=yes \\
    ipsec-secret={$psk} \\
    allow-fast-path=yes \\
    disabled=no

# Add route to VPN server (adjust gateway as needed)
/ip route add \\
    dst-address=192.168.47.0/24 \\
    gateway=l2tp-out1 \\
    comment="VPN tunnel route"

# Firewall rules for VPN traffic
/ip firewall filter add \\
    chain=input \\
    in-interface=l2tp-out1 \\
    action=accept \\
    comment="Accept VPN traffic"

/ip firewall filter add \\
    chain=forward \\
    in-interface=l2tp-out1 \\
    action=accept \\
    comment="Allow VPN forwarding"

ROUTEROS;

        return $script;
    }

    /**
     * Generate QR code data for easy mobile configuration.
     */
    public function generateQRData(Mikrotik $mikrotik): string
    {
        return json_encode([
            'server' => config('vpnpanel.domain'),
            'username' => $mikrotik->vpn_username,
                'password' => $mikrotik->vpnPassword(),
            'ip' => $mikrotik->vpn_ip,
            'psk' => config('vpnpanel.psk'),
        ]);
    }

    /**
     * Generate connection summary.
     */
    public function generateSummary(Mikrotik $mikrotik): array
    {
        return [
            'vpn_server' => config('vpnpanel.domain'),
            'username' => $mikrotik->vpn_username,
                'password' => $mikrotik->vpnPassword(),
            'vpn_ip' => $mikrotik->vpn_ip,
            'psk' => config('vpnpanel.psk'),
            'winbox_url' => $mikrotik->winbox_url,
            'webfig_url' => $mikrotik->webfig_url,
        ];
    }

    /**
     * Export script to file.
     */
    public function exportToFile(Mikrotik $mikrotik, string $path): void
    {
        $script = $this->generate($mikrotik);
        file_put_contents($path, $script);
    }

    private function now(): string
    {
        return now()->toDateTimeString();
    }
}
