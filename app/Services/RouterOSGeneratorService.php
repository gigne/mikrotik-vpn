<?php

declare(strict_types=1);

namespace App\Services;

use App\Models\Mikrotik;

/**
 * Generates RouterOS configuration scripts for MikroTik.
 *
 * Each site gets a unique, descriptive interface name derived from its
 * site name (e.g. `l2tp-vpn-kantor`), never a generic placeholder like
 * `l2tp-out1`, so multiple tunnels stay identifiable on the router.
 */
class RouterOSGeneratorService
{
    /**
     * Generate complete RouterOS script for an L2TP/IPSec client.
     */
    public function generate(Mikrotik $mikrotik): string
    {
        $vpnServer = config('vpnpanel.domain');
        $username = $mikrotik->vpn_username;
        $password = $mikrotik->vpnPassword();
        $ip = $mikrotik->vpn_ip;
        $psk = config('vpnpanel.psk');
        $ifName = $this->interfaceName($mikrotik);
        $vpnSubnet = config('vpnpanel.ip_pool.subnet', '192.168.47.0/24');

        return <<<ROUTEROS
# RouterOS L2TP/IPSec Client Configuration
# Generated by VPN Panel on {$this->now()}
# Site: {$mikrotik->site_name}
# VPN Server: {$vpnServer}
# Username: {$username}
# VPN IP: {$ip}
# Interface: {$ifName}

# Remove any previous L2TP client for this site (safe to re-run)
/interface l2tp-client remove [find name="{$ifName}"]

# IPsec Phase 2 compatibility: the VPN server (Libreswan 5.x) rejects the
# RouterOS default proposal (pfs-group=modp1024, removed from Libreswan).
# Align the default proposal with the server before bringing the tunnel up.
/ip ipsec proposal set [find default=yes] pfs-group=modp2048

# Create L2TP client interface
/interface l2tp-client add \\
    name={$ifName} \\
    connect-to={$vpnServer} \\
    user={$username} \\
    password={$password} \\
    use-ipsec=yes \\
    ipsec-secret={$psk} \\
    allow-fast-path=yes \\
    disabled=no

# Route to the VPN subnet through this tunnel
/ip route add \\
    dst-address={$vpnSubnet} \\
    gateway={$ifName} \\
    comment="VPN tunnel route for {$mikrotik->site_name}"

# Firewall: accept inbound traffic arriving on the tunnel
/ip firewall filter add \\
    chain=input \\
    in-interface={$ifName} \\
    action=accept \\
    comment="Accept VPN input for {$mikrotik->site_name}"

/ip firewall filter add \\
    chain=forward \\
    in-interface={$ifName} \\
    action=accept \\
    comment="Allow VPN forwarding for {$mikrotik->site_name}"

ROUTEROS;
    }

    /**
     * Generate QR code data for easy mobile configuration.
     */
    public function generateQRData(Mikrotik $mikrotik): string
    {
        return json_encode([
            'server' => config('vpnpanel.domain'),
            'username' => $mikrotik->vpn_username,
            'password' => $mikrotik->vpnPassword(),
            'ip' => $mikrotik->vpn_ip,
            'psk' => config('vpnpanel.psk'),
        ]);
    }

    /**
     * Generate a human-readable connection summary.
     *
     * @return array<string, mixed>
     */
    public function generateSummary(Mikrotik $mikrotik): array
    {
        return [
            'vpn_server' => config('vpnpanel.domain'),
            'username' => $mikrotik->vpn_username,
            'password' => $mikrotik->vpnPassword(),
            'vpn_ip' => $mikrotik->vpn_ip,
            'psk' => config('vpnpanel.psk'),
            'interface' => $this->interfaceName($mikrotik),
            'winbox_url' => $mikrotik->winbox_url,
            'webfig_url' => $mikrotik->webfig_url,
        ];
    }

    /**
     * Export script to a file.
     */
    public function exportToFile(Mikrotik $mikrotik, string $path): void
    {
        file_put_contents($path, $this->generate($mikrotik));
    }

    /**
     * Derive a unique, descriptive L2TP interface name from the site name.
     *
     * RouterOS interface names allow letters, digits, hyphens and
     * underscores, max 32 characters. The result is deterministic per site
     * so re-running the script targets the same interface.
     */
    private function interfaceName(Mikrotik $mikrotik): string
    {
        $slug = preg_replace('/[^a-zA-Z0-9_-]/', '-', $mikrotik->site_name) ?? 'site';
        $slug = preg_replace('/-+/', '-', $slug);
        $slug = strtolower(trim($slug, '-'));

        if ($slug === '') {
            $slug = 'site';
        }

        $name = 'l2tp-vpn-' . $slug;

        return strlen($name) > 32 ? substr($name, 0, 32) : $name;
    }

    private function now(): string
    {
        return now()->toDateTimeString();
    }
}
