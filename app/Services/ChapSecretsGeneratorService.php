<?php

declare(strict_types=1);

namespace App\Services;

use App\Models\Mikrotik;
use App\Models\VpnUser;

/**
 * Generates /etc/ppp/chap-secrets content from the database.
 *
 * The database is the single source of truth for this file. Two kinds of
 * accounts are emitted:
 *
 *  - MikroTik branches: always carry a static VPN IP and store their password
 *    encrypted, so they win any username collision.
 *  - Standalone VPN users: either a static IP (when `assigned_ip` is set) or a
 *    dynamic one (`*`), letting xl2tpd hand out an address from its pool.
 */
class ChapSecretsGeneratorService
{
    /** Server field written for every entry; matches xl2tpd's `name = l2tpd`. */
    private const SERVER = 'l2tpd';

    /** chap-secrets wildcard meaning "assign the address dynamically". */
    private const DYNAMIC_IP = '*';

    /**
     * Generate the full chap-secrets file content.
     */
    public function generate(): string
    {
        $header = [
            '# Secrets for PPP connections',
            '# Generated by VPN Panel - do not edit by hand.',
            '# ' . now()->toDateTimeString(),
            '#',
            '# Format: "username" server "password" ip_address',
            '# An ip_address of "*" means the address is assigned dynamically',
            '# from the xl2tpd pool.',
            '#',
        ];

        $entries = [];

        // MikroTik branches first: they own their username and static IP.
        foreach (Mikrotik::orderBy('vpn_username')->get() as $mikrotik) {
            $entries[$mikrotik->vpn_username] = $this->formatEntry(
                $mikrotik->vpn_username,
                $mikrotik->vpnPassword(),
                $mikrotik->vpn_ip,
            );
        }

        // Standalone VPN users, skipping usernames already claimed by a MikroTik.
        $vpnUsers = VpnUser::query()
            ->active()
            ->whereNotIn('username', array_keys($entries))
            ->orderBy('username')
            ->get();

        foreach ($vpnUsers as $user) {
            $entries[$user->username] = $this->formatEntry(
                $user->username,
                $user->password,
                $user->assigned_ip ?? self::DYNAMIC_IP,
            );
        }

        ksort($entries);

        return implode("\n", [...$header, ...array_values($entries)]) . "\n";
    }

    /**
     * Validate chap-secrets content.
     *
     * @return list<string> human-readable problems; empty when valid
     */
    public function validate(string $content): array
    {
        $errors = [];

        foreach (explode("\n", $content) as $index => $rawLine) {
            $line = trim($rawLine);

            if ($line === '' || str_starts_with($line, '#')) {
                continue;
            }

            $lineNumber = $index + 1;

            if (! preg_match('/^"([^"]+)"\s+(\S+)\s+"([^"]*)"\s+(\S+)$/', $line, $matches)) {
                $errors[] = "Line {$lineNumber}: invalid format";
                continue;
            }

            $username = $matches[1];
            $ip = $matches[4];

            if (! preg_match('/^[A-Za-z0-9_.\-]+$/', $username)) {
                $errors[] = "Line {$lineNumber}: username may only contain letters, digits and . _ -";
            }

            if ($ip !== self::DYNAMIC_IP && filter_var($ip, FILTER_VALIDATE_IP, FILTER_FLAG_IPV4) === false) {
                $errors[] = "Line {$lineNumber}: address must be a valid IPv4 or '*'";
            }
        }

        return $errors;
    }

    private function formatEntry(string $username, string $password, string $ip): string
    {
        return sprintf(
            '"%s" %s "%s" %s',
            $this->escape($username),
            self::SERVER,
            $this->escape($password),
            $ip === self::DYNAMIC_IP ? self::DYNAMIC_IP : $this->escape($ip),
        );
    }

    /**
     * Strip characters that would break the quoted chap-secrets field.
     *
     * Backslashes are removed rather than escaped because pppd does not
     * reliably interpret escapes inside these fields.
     */
    private function escape(string $value): string
    {
        return str_replace(['"', '\\', "\n", "\r", "\t"], '', $value);
    }
}
